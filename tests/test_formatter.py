class TestFormatReviewMarkdown:

    def test_contains_header(self, sample_result):
        output = format_review_markdown(sample_result)
        assert "코드 리뷰 결과" in output

    def test_contains_score(self, sample_result):
        output = format_review_markdown(sample_result)
        assert "7/10" in output

    def test_contains_summary(self, sample_result):
        output = format_review_markdown(sample_result)
        assert "테스트 요약" in output

    def test_contains_comments(self, sample_result):
        output = format_review_markdown(sample_result)
        assert "main.py" in output
        assert "초기화" in output

    def test_empty_comments(self, empty_result):
        output = format_review_markdown(empty_result)
        assert "특이사항 없음" in output


