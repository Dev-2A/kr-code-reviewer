class TestGetScoreGrade:

    def test_excellent(self):
        assert "훌륭" in _get_score_grade(9)
        assert "훌륭" in _get_score_grade(10)

    def test_good(self):
        assert "양호" in _get_score_grade(7)
        assert "양호" in _get_score_grade(8)

    def test_needs_improvement(self):
        assert "개선" in _get_score_grade(5)
        assert "개선" in _get_score_grade(6)

    def test_critical(self):
        assert "심각" in _get_score_grade(1)
        assert "심각" in _get_score_grade(4)

    def test_zero(self):
        assert "평가 불가" in _get_score_grade(0)


